#!/usr/bin/env python3
"""Project runtime views for DoddleOS workspaces (read-only projections).

Source of truth stays in Skills/ (monorepo: doddle-core + doddle-*/ packs).
This script only writes generated indexes/views into the sibling dirs:

  Blueprints/  <- index of every blueprint.yaml (no copies)
  Graphs/      <- call-graph + per-skill DAG as mermaid (derived from nodes)
  SOPs/        <- SOP index extracted from SKILL.md (when-to-use + I/O)
  WorkFlows/   <- index of .claude/workflows + agents + commands

Usage (either layout):
  python3 scripts/project-artifacts.py [--clean]   # from Skills repo root
  python3 project-artifacts.py [--clean]           # from workspace root (parent of Skills/)

Stdlib only. Never moves/deletes sources. Generated files carry a header.
"""
import argparse
import datetime
import json
import re
import sys
from pathlib import Path


def find_skills_root(start: Path) -> Path:
    for d in [start, *start.parents]:
        if (d / "doddle-core" / "scripts" / "validate.py").exists():
            return d
    sys.exit(f"Skills root not found above {start} (expected doddle-core/scripts/validate.py)")


SKILLS_ROOT = find_skills_root(Path(__file__).resolve().parent)
OUT_ROOT = SKILLS_ROOT.parent
OUT_DIRS = {
    "blueprints": OUT_ROOT / "Blueprints",
    "graphs": OUT_ROOT / "Graphs",
    "sops": OUT_ROOT / "SOPs",
    "workflows": OUT_ROOT / "WorkFlows",
}

GENERATED = (
    "<!-- GENERATED by project-artifacts.py — do not edit. "
    "Source of truth: Skills/. Re-run: python3 project-artifacts.py -->\n"
)
FM_RE = re.compile(r"^---\n(.*?)\n---", re.S)


def parse_fm(text: str) -> dict:
    m = FM_RE.search(text)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def section(text: str, key: str) -> str:
    m = re.search(r"^" + re.escape(key) + r":\s*\n((?:[ \t]+.*\n?)*)", text, re.M)
    return m.group(1) if m else ""


def parse_inline_list(sec: str, field: str) -> list:
    """Parse `{name: x, ...}` or `{id: y, ...}` entries in a yaml section."""
    vals = []
    for lit in re.findall(r"\{[^{}]*\}", sec):
        m = re.search(rf"{field}:\s*([^\s,}}]+)", lit)
        if m:
            vals.append(m.group(1).strip().strip("\"'"))
    return vals


def parse_nodes(bp_text: str) -> list:
    nodes = []
    sec = section(bp_text, "nodes")
    # Line-based: each node is a '- {...}' line; may contain nested inputs: {...}.
    # Brace-based findall splits those, so prefer lines starting with '-'.
    lits = [ln.strip() for ln in sec.splitlines() if ln.strip().startswith("-")]
    if not lits:
        lits = [lit for lit in re.findall(r"\{[^{}]*\}", sec) if "id:" in lit]
    for lit in lits:
        def f(k):
            m = re.search(rf"{k}:\s*([^\s,}}]+)", lit)
            return m.group(1).strip().strip("\"'") if m else ""
        nid, ntype, ref = f("id"), f("type"), f("ref")
        if not nid or not ntype:
            continue
        needs = re.search(r"needs:\s*\[([^\]]*)\]", lit)
        prod = re.search(r"produces:\s*\[([^\]]*)\]", lit)
        nodes.append({
            "id": nid, "type": ntype, "ref": ref,
            "needs": [x.strip() for x in needs.group(1).split(",") if x.strip()] if needs else [],
            "produces": [x.strip() for x in prod.group(1).split(",") if x.strip()] if prod else [],
        })
    return nodes


def discover_skills() -> list:
    dirs = sorted((SKILLS_ROOT).glob("doddle-*/.claude/skills/*/"))
    dirs += sorted((SKILLS_ROOT / ".claude" / "skills").glob("*/")) if (SKILLS_ROOT / ".claude" / "skills").exists() else []
    skills = []
    for d in dirs:
        if not d.is_dir():
            continue
        sk, bp = d / "SKILL.md", d / "blueprint.yaml"
        if not sk.exists() or not bp.exists():
            continue
        fm = parse_fm(sk.read_text(encoding="utf-8", errors="replace"))
        bt = bp.read_text(encoding="utf-8", errors="replace")
        m_id = re.search(r"^id:\s*(\S+)", bt, re.M)
        m_ver = re.search(r"^version:\s*(\S+)", bt, re.M)
        m_desc = re.search(r'^description:\s*["\']?(.*?)["\']?\s*$', bt, re.M)
        nodes = parse_nodes(bt)
        tools = parse_inline_list(section(bt, "tools"), "id")
        skills.append({
            "id": fm.get("id") or (m_id.group(1) if m_id else d.name),
            "version": fm.get("version") or (m_ver.group(1) if m_ver else "?"),
            "description": fm.get("description") or (m_desc.group(1) if m_desc else ""),
            "pack": d.parts[d.parts.index("Skills") + 1] if "Skills" in d.parts else "?",
            "skill_dir": d.name,
            "source_skill": str(d.relative_to(OUT_ROOT).as_posix()) + "/SKILL.md",
            "source_blueprint": str(d.relative_to(OUT_ROOT).as_posix()) + "/blueprint.yaml",
            "inputs": parse_inline_list(section(bt, "inputs"), "name"),
            "outputs": parse_inline_list(section(bt, "outputs"), "name"),
            "tools": tools,
            "integrations": re.findall(r"^\s*-\s*([\w-]+)\s*$", section(bt, "integrations"), re.M),
            "nodes": nodes,
            "calls": [n["ref"] for n in nodes if n["type"] == "call"],
        })
    # de-dupe document-skills sub-variants keep all; sort by id
    skills.sort(key=lambda s: s["id"])
    return skills


def discover_ops() -> dict:
    cl = SKILLS_ROOT / ".claude"
    workflows = sorted([p.name for p in (cl / "workflows").glob("*.md")]) if (cl / "workflows").exists() else []
    agents = sorted([p.stem for p in (cl / "agents").glob("*.md")]) if (cl / "agents").exists() else []
    cmds = sorted([str(p.relative_to(cl / "commands").as_posix()) if isinstance(cl / "commands", Path) else p.name
                   for p in (cl / "commands").rglob("*.md")]) if (cl / "commands").exists() else []
    # rglob relative fix
    cmds = sorted([str(p.relative_to(cl / "commands")) for p in (cl / "commands").rglob("*.md")]) if (cl / "commands").exists() else []
    return {"workflows": workflows, "agents": agents, "commands": cmds}


def write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def gen_blueprints(skills: list, stamp: str):
    lines = [GENERATED, f"# Blueprints Index — {len(skills)} skills ({stamp})\n",
             "> Read-only view. Sources live in `../Skills/`. Do not copy files here.\n",
             "| Skill ID | Ver | Pack | Inputs | Outputs | Tools | Source |",
             "|---|---|---|---|---|---|---|"]
    for s in skills:
        lines.append(f"| `{s['id']}` | {s['version']} | {s['pack']} | {len(s['inputs'])} | {len(s['outputs'])} | {len(s['tools'])} | `../{s['source_blueprint']}` |")
    write(OUT_DIRS["blueprints"] / "BLUEPRINTS_INDEX.md", "\n".join(lines) + "\n")
    write(OUT_DIRS["blueprints"] / "blueprints.json", json.dumps(
        {"generated": stamp, "source_root": "Skills", "count": len(skills), "blueprints": skills}, indent=2) + "\n")


def mermaid_for(s: dict) -> str:
    rows = ["flowchart LR"]
    for n in s["nodes"]:
        label = f"{n['id']}[{n['type']}:{n['ref'] or n['id']}]" if n["ref"] else f"{n['id']}[{n['type']}]"
        rows.append(f"  {s['id'].replace('.', '_')}_{n['id']}[\"{n['id']} ({n['type']})\"]")
    for n in s["nodes"]:
        for dep in n["needs"]:
            if dep == "inputs":
                rows.append(f"  IN((inputs)) --> {s['id'].replace('.', '_')}_{n['id']}")
            else:
                rows.append(f"  {s['id'].replace('.', '_')}_{dep} --> {s['id'].replace('.', '_')}_{n['id']}")
    return "\n".join(rows)


def gen_graphs(skills: list, stamp: str):
    edges = [(s["id"], c) for s in skills for c in s["calls"]]
    lines = [GENERATED, f"# Call Graph — {len(skills)} skills, {len(edges)} call edges ({stamp})\n",
             "> Derived from `nodes: type: call` in `../Skills/doddle-*/.claude/skills/*/blueprint.yaml`.\n",
             "```mermaid", "flowchart LR"]
    ids = {s["id"] for s in skills}
    for a, b in edges:
        style = "" if b in ids else ":::missing"
        lines.append(f"  {a.replace('.', '_')}[{a}] --> {b.replace('.', '_')}[{b}]{style}")
    lines += ["```\n", "## Per-skill DAGs (agent/tool/call/gate)\n"]
    for s in skills:
        lines += [f"### `{s['id']}`\n", "```mermaid", mermaid_for(s), "```\n"]
    write(OUT_DIRS["graphs"] / "CALL_GRAPH.md", "\n".join(lines))
    write(OUT_DIRS["graphs"] / "call-graph.json", json.dumps(
        {"generated": stamp, "skills": len(skills), "edges": [{"from": a, "to": b} for a, b in edges]}, indent=2) + "\n")


def gen_sops(skills: list, stamp: str):
    lines = [GENERATED, f"# SOPs Index — {len(skills)} skills ({stamp})\n",
             "> SOP view = SKILL.md When-to-Use + I/O. Full procedure stays in `../Skills/`.\n",
             "| Skill ID | When to use (description) | Inputs → Outputs | SOP source |",
             "|---|---|---|---|"]
    for s in skills:
        desc = s["description"].replace("|", "\\|")[:160]
        lines.append(f"| `{s['id']}` | {desc} | {', '.join(s['inputs'][:4])} → {', '.join(s['outputs'][:4])} | `../{s['source_skill']}` |")
    write(OUT_DIRS["sops"] / "SOPS_INDEX.md", "\n".join(lines) + "\n")
    write(OUT_DIRS["sops"] / "sops.json", json.dumps(
        {"generated": stamp, "count": len(skills),
         "sops": [{"id": s["id"], "description": s["description"], "inputs": s["inputs"],
                   "outputs": s["outputs"], "source": s["source_skill"]} for s in skills]}, indent=2) + "\n")


def gen_workflows(ops: dict, stamp: str):
    lines = [GENERATED, f"# WorkFlows Index ({stamp})\n",
             f"> Sources: `../Skills/.claude/workflows/`, `../Skills/.claude/agents/`, `../Skills/.claude/commands/`.\n",
             f"## Workflows ({len(ops['workflows'])})"]
    lines += [f"- `{w}` — `../Skills/.claude/workflows/{w}`" for w in ops["workflows"]]
    lines += [f"\n## Agents ({len(ops['agents'])})", ", ".join(f"`{a}`" for a in ops["agents"])]
    lines += [f"\n## Commands ({len(ops['commands'])}) — by category"]
    cats: dict = {}
    for c in ops["commands"]:
        cat = c.split("/")[0] if "/" in c else "(root)"
        cats.setdefault(cat, []).append(c)
    for cat in sorted(cats):
        lines.append(f"- `{cat}` ({len(cats[cat])}): " + ", ".join(f"`{c}`" for c in cats[cat][:12]) + (" …" if len(cats[cat]) > 12 else ""))
    write(OUT_DIRS["workflows"] / "WORKFLOWS_INDEX.md", "\n".join(lines) + "\n")
    write(OUT_DIRS["workflows"] / "workflows.json", json.dumps({"generated": stamp, **ops}, indent=2) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clean", action="store_true", help="remove generated index files only")
    args = ap.parse_args()
    targets = ["BLUEPRINTS_INDEX.md", "blueprints.json", "CALL_GRAPH.md", "call-graph.json",
               "SOPS_INDEX.md", "sops.json", "WORKFLOWS_INDEX.md", "workflows.json"]
    if args.clean:
        n = 0
        for d in OUT_DIRS.values():
            for t in targets:
                p = d / t
                if p.exists():
                    p.unlink()
                    n += 1
        print(f"cleaned {n} generated files (sources untouched)")
        return
    if not SKILLS_ROOT.exists():  # unreachable (found by construction), kept as guard
        sys.exit(f"Skills root not found: {SKILLS_ROOT}")
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%MZ")
    skills = discover_skills()
    if not skills:
        sys.exit("no skills found — nothing to project")
    ops = discover_ops()
    gen_blueprints(skills, stamp)
    gen_graphs(skills, stamp)
    gen_sops(skills, stamp)
    gen_workflows(ops, stamp)
    print(f"projected {len(skills)} skills, {len(ops['workflows'])} workflows, "
          f"{len(ops['agents'])} agents, {len(ops['commands'])} commands -> "
          f"Blueprints/ Graphs/ SOPs/ WorkFlows/ (8 files, sources untouched)")


if __name__ == "__main__":
    main()
